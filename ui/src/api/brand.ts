/**
 * العشريّ نوعٌ موسوم لا `string` عاديّ — ADR-009.
 *
 * الخلفية تُرجِع **٣٣ حقلًا** عشريًّا نصًّا (`fields.Decimal(as_string=True)`)،
 * وبجوارها في **الكائن نفسه** أرقامٌ حقيقية. في ردّ `GET /me/deck` وحده:
 * `hours` و`remaining` و`at_hours` نصوص، و`progress_pct` رقم.
 *
 * وخلطُهما لا يرفع خطأً في JavaScript: `hours - remaining` يعطي `NaN`،
 * و`Number(hours)` يعمل بصمت ويفقد الدقّة عند الحدود. **ولا يمسكه اختبارٌ
 * سلوكيّ** (الشاشة تُرسَم) **ولا فحص AST** (لا مقارنة ولا رقم مجال) — يمسكه
 * فقط أن يرى طالبٌ رقمًا خاطئًا في بطاقته.
 *
 * والوسم يجعله خطأ ترجمة. وكلفتُه **صفر وقت التشغيل**: `unique symbol` في
 * موضع نوعٍ فقط، لا يُولَّد منه أي كود.
 */

declare const DECIMAL: unique symbol

/**
 * قيمة عشرية وصلت نصًّا من الخادم — `"611.25"`.
 *
 * لا تدخل عملية حسابية، ولا تُمرَّر مكان رقم، ولا يُنتجها `String(x)` عرضًا:
 * الوسم يرفض `string` العاديّ أيضًا، فلا يتسلّل ناتج `Number()` عائدًا.
 * وتحويلُها إلى نصٍّ معروض يمرّ بـ`api/format.ts` وحده.
 */
export type Decimal = string & { readonly [DECIMAL]: 'decimal' }

/**
 * نسبة مئوية **رقمًا حقيقيًّا** — `progress_pct` · `percent` · `size_pct`.
 *
 * اسمٌ مستقلّ لا `number` عارٍ: يجعل الفارق بين العشريّ والنسبة مقروءًا في
 * توقيع الحقل نفسه لا في ذاكرة القارئ.
 */
export type Pct = number

/** عدّ صحيح — أعضاء · أيام · ترتيب. */
export type Count = number

/**
 * **الباب الوحيد** الذي يدخل منه نصٌّ خام إلى نوع `Decimal`: حدّ الشبكة.
 *
 * تُستعمل في `api/client.ts` عند وصول الردّ، ولا تُستعمل في شاشة أبدًا —
 * استعمالُها في شاشة يعني أن رقمًا وُلِّد محليًّا، وهو ما تمنعه القاعدة ٥.
 */
export const asDecimal = (raw: string): Decimal => raw as Decimal
