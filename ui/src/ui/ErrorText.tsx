import type { ReactNode } from 'react'

/**
 * @covers ق-٢٨٨
 *
 * رسالةُ خطأٍ من الخادم، معلَنةً للقارئ الآليّ بـ`role="alert"`.
 *
 * **وُجدت لأن الكتلة نفسها كانت مكرَّرةً إحدى وثلاثين مرّةً حرفيًّا** في
 * `src/screens/` — أكبر تكرارٍ ميكانيكيّ في المستودع. وطبقةُ البدائيات كانت
 * قد توقّفت عند المرئيّ (`Placard` · `Field` · `Button`) ولم تُغطِّ **عرضَ
 * الخطأ**، فتكفّلت به كلُّ شاشةٍ بيدها.
 *
 * و`role="alert"` هو الجزءُ الذي يُنسى: نسخةٌ واحدةٌ بلا السمة تعني خطأً لا
 * يسمعه قارئُ الشاشة أبدًا — عطلُ وصولٍ لا يراه فحصٌ بصريّ.
 *
 * **و`spacing` يُمرَّر ولا يُوحَّد:** النسخُ الإحدى والثلاثون استعملت **سبعة
 * هوامش مختلفة** (`mb-3` إحدى عشرة مرّة · بلا هامش تسعًا · `mt-3` أربعًا ·
 * `mt-1` مرّتين · `mb-4` مرّتين · `mt-2` · `mb-2`). وفرضُ هامشٍ واحدٍ عليها
 * **تغييرُ تصميمٍ باسم تنظيفٍ** — فالقيمة تبقى عند موضع النداء، والمشترك هو
 * البنية والسمة وحدهما. وTailwind يرى الصنف في ملفّ النداء فيُصدِره.
 */
export default function ErrorText({
  children,
  spacing = 'mb-3',
}: {
  children: ReactNode
  /** صنفُ هامشٍ من Tailwind، أو `''` لبلا هامش. */
  spacing?: string
}) {
  if (!children) return null
  return (
    <p role="alert" className={`${spacing} text-[13px] text-(--color-red-text)`}>
      {children}
    </p>
  )
}
