"""
مُشتركاتُ طبقة المسارات — **حدُّ تنسيقٍ لا مكان قواعد**.

وُجد هذا الملفّ لأن `routes/admin.py:106` كان يملك `_org()` ويستعمله تسعًا
وثلاثين مرّة، و`routes/me.py` **يكتب السطر نفسه اثنتي عشرة مرّةً سطريًّا** —
نفسُ الاستعلام، مرّةً بخطّافٍ ومرّةً بلا.

وليس التكرارُ وحده الثمن: تغييرُ طريقة حلّ الجمعية (تخزينًا في `g` مثلًا، أو
فحصًا إضافيًّا) كان يعني موضعًا واحدًا في `admin.py` **واثنَي عشر في `me.py`**
— فيُنسى أحدها ويفترق مسارٌ عن بقيّته بلا أن يسقط اختبار.
"""

from flask import g

from ..extensions import db
from ..models import Org


def org_of_session() -> Org:
    """
    جمعيةُ صاحب الجلسة.

    **ولا معرّفَ من الطلب أبدًا** — لا في المسار ولا في الاستعلام ولا في
    الجسم. وهذا أقوى من التحقّق من الملكية: يُلغي المسارَ الذي يحتاج تحقّقًا
    (`SECURITY.md §٧.٣`).

    و`db.session.get` يقرأ من خريطة الهوية إن كان الكائن محمَّلًا، فالنداءُ
    مرّتين في الطلب نفسه لا يُنتج استعلامًا ثانيًا.
    """
    return db.session.get(Org, g.user.org_id)
