"""
خطأُ العمل — **صنفٌ واحدٌ أساسٌ لعشرة كانت منسوخة**.

كانت عشرةُ خدماتٍ تحمل الصنف نفسه، **ثمانيةٌ منها متطابقةٌ بايتًا بايت** بما
فيها التعليقُ الذي يُعلن النسخ («نمط `ReadingError`»). واثنتان تختلفان في
شيءٍ واحد: `status` بلا افتراض — فصار للمفهوم الواحد نداءان.

**والوراثةُ لا الاستبدال.** كلُّ خدمةٍ تُبقي اسمَها (`ReadingError` ·
`FuelError` …) لأن المسارات تُلقّط باسمٍ بعينه:

    except reading_service.ReadingError as exc:
        abort(exc.status, message=str(exc))

وتوحيدُها في اسمٍ واحد يجعل مسارَ القراءة يلتقط خطأ الوقود، فيردّ ٤٢٢ برسالةٍ
من نطاقٍ آخر — **خسارةُ دقّةٍ لا ربحُ تنظيف**. فالمشترك هو **العقد** (`status`
ورسالةٌ عربية) لا الاسم.

**ولا يعرف HTTP:** `status` عددٌ يُفسّره المسار، والخدمةُ لا تستورد `flask`
ولا `abort`. هذا ما يجعل الخدمات قابلةً للاستدعاء من `flask bootstrap-org`
ومن الاختبارات بلا طلبٍ ولا سياق.

وعقدُ الأخطاء كلُّه في `docs/design/ARCHITECTURE.md §٦`.
"""


class ServiceError(Exception):
    """
    خطأُ عملٍ يُترجَم إلى رمز حالة في المسار.

    و`422` افتراضًا لأنها الحالةُ الغالبة: «الطلبُ مفهومٌ وقاعدةُ عملٍ ترفضه»
    — بخلاف `404` (لا سجلّ) و`409` (تعارضٌ أو تكرار) و`429` (حدٌّ).
    """

    def __init__(self, message: str, status: int = 422):
        self.status = status
        super().__init__(message)
