#!/usr/bin/env bash
#
# @covers ق-٢١١
#
# بوابة التتبّع الميكانيكي لـ`SLICE-01` §٨.
#
# العلاقة المفروضة:   معيار  →  مالك تحقّق معلَن  →  دليل
#
# **لماذا لا يكفي أن نتذكّر؟** لأن البوابة تُقرأ بالعين: حذفُ اختبارٍ لا يُسقطها،
# فتبقى تقول «مكتملة» بلا تغطية. هذا السكربت يجعل الرابط إلزاميًّا:
#
#   · المصدر الوحيد للمعايير: جدول §٧ في `docs/plans/SLICE-01.md`.
#   · المصدر الوحيد للتغطية: وسم `@covers ق-N` داخل ملفّ التحقّق نفسه.
#   · معيارٌ بلا مالك ⇒ سقوط. ومالكٌ يعلن معيارًا غير معلَن ⇒ سقوط.
#
# **الوسم داخل الملفّ لا في اسمه:** نقلُ اختبارٍ أو إعادة تسميته لا تكسر البوابة،
# وحذفُ وسمه يكسرها — وهو المطلوب.
#
# **ولا نجاح على فراغ:** استخراجٌ يعطي صفر معايير عطلٌ في الفحص لا نجاحٌ له —
# وقد وقع هذا فعلًا عند بناء السكربت (فشل محليّة صامت أعطى ✅ على لا شيء).
set -uo pipefail
export LC_ALL=C.UTF-8   # الأرقام العربية-الهندية متعدّدة البايتات: بلا هذا يفشل النطاق

# رُقّي من `web/scripts/` إلى جذر المستودع في و-١٣: هو بوابة تتبّع **للمستودع
# كلّه** لا للواجهة، وبقاؤه داخل `web/` — وقد صار مرجعًا مجمَّدًا — يجعل نسخته
# الوحيدة رهينة مجلّد متروك. فصار الجذر مستوًى واحدًا فوقه لا اثنين.
#
# **ويحرسه فحصُ البيان أدناه:** جذرٌ خاطئ لا يجد `docs/plans/SLICE-01.md`
# فيسقط صاخبًا بـ`exit 2` — لا يمرّ صامتًا على مستودعٍ لا يخصّه.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# ═══════════════════════════════════════════════════════════════════════════
# بيان الخطط الفاعلة.
#
# كان مثبَّتًا على `SLICE-01.md` وحده، فمعايير أي وحدة تالية تبقى خارج البوابة
# بلا إنذار. و`SLICE-01.md` **مجمَّد كوحدة مغلقة** فلا تُضاف إليه معايير جديدة،
# فصار البيان: الشريحة المغلقة + كل خطّة وحدة فاعلة.
#
# **والملفّ الغائب عطلٌ لا صمت:** بيانٌ يشير إلى ملفّ غير موجود يوقف البوابة،
# لأن اختفاء خطّةٍ يعني اختفاء معاييرها — وهو ما وُجدت البوابة لتمنعه.
# ═══════════════════════════════════════════════════════════════════════════
MANIFEST=("$ROOT/docs/plans/SLICE-01.md")
for plan in "$ROOT"/docs/slices/*.md; do
  [ -e "$plan" ] && MANIFEST+=("$plan")
done
# مواضع المالكين. `ui/` أُضيف في و-١٣، و**المجلّد الغائب يُتخطّى لا يُسقِط**:
# البوابة تعمل على مستودعٍ لم تُنشأ فيه `ui/` بعد (نقطة التفتيش ١)، والحارس
# الحقيقيّ ضدّ الفراغ هو `MIN_CRITERIA` أدناه لا وجودُ مجلّد بعينه.
#
# **و`$ROOT/scripts` أُضيف بعد ثغرةٍ أحدثتها الترقية نفسها:** حين انتقل هذا
# السكربت من `web/scripts/` إلى هنا، صار يبحث في كل مكانٍ **إلّا مكانه** —
# فوسمُه هو (`@covers ق-٢١١`) غير مرئيّ لنفسه. بوابةٌ عمياء عن ذاتها تُبلّغ عن
# معيارها «بلا مالك» وهو مملوك، فيبدو العطل في المعيار لا في البوابة.
SEARCH=()
for dir in "$ROOT/api/tests" "$ROOT/scripts" "$ROOT/web/src/test" "$ROOT/web/scripts" \
           "$ROOT/ui/src" "$ROOT/ui/scripts"; do
  [ -d "$dir" ] && SEARCH+=("$dir")
done

# المصدر وحده. الوسم يعيش في الكود المكتوب لا في مخرَجه المترجَم، و`__pycache__`
# يحمل نسخًا قديمة من النصوص التوثيقية. (`grep` يرفض اليوم إخراج مطابقات من ملفّ
# ثنائي فلا تمرير كاذب — لكن الاعتماد على ذلك اعتمادٌ على تفصيل أداة، والنطاق
# الصحيح أصلًا هو المصدر.)
#
# **`*.ts` و`*.tsx` أُضيفا في و-١٣** — وغيابُهما كان يجعل كل وسمٍ في الواجهة
# الجديدة **غير مرئيّ تمامًا** ولو أُضيف مجلّدها إلى `SEARCH`: عمًى مزدوج، كلٌّ
# منه كافٍ وحده لجعل «أخضر» بلا معنى (مُثبَت عدائيًّا، ق-٢١١).
SOURCES=(--include='*.py' --include='*.js' --include='*.jsx' --include='*.mjs' \
         --include='*.sh' --include='*.ts' --include='*.tsx')
DIGITS='[٠١٢٣٤٥٦٧٨٩]'
MIN_CRITERIA=16   # حارس الفراغ: و-١ وحدها ١٦ — استخراجٌ دونها عطلٌ لا نجاح

for plan in "${MANIFEST[@]}"; do
  [ -f "$plan" ] || { echo "❌ خطّة مفقودة من البيان: $plan"; exit 2; }
done

# **من §٧ وحده.** جداول §٨ تعيد ذكر المعايير في خريطة الملكية، فقراءة الملفّ
# كلّه تجعل معيارًا محذوفًا من §٧ يبقى محسوبًا لأنه ما زال مذكورًا في الخريطة —
# فيختفي من المصدر المخوَّل بلا إنذار. النطاق: من عنوان §٧ إلى عنوان §٨.
declared=$(
  for plan in "${MANIFEST[@]}"; do
    sed -n '/^## ٧\. معايير القبول/,/^## ٨\. الاختبار/p' "$plan"
  done | grep -oE "^\| \*{0,2}ق-$DIGITS+" | grep -oE "ق-$DIGITS+" | sort -u
)
covered=$(grep -rhoE "${SOURCES[@]}" "@covers +ق-$DIGITS+(, *ق-$DIGITS+)*" "${SEARCH[@]}" 2>/dev/null \
          | grep -oE "ق-$DIGITS+" | sort -u)

n_declared=$(printf '%s\n' "$declared" | grep -c . || true)
n_covered=$(printf '%s\n' "$covered" | grep -c . || true)

echo "═══ تتبّع بوابة الوحدات ═══"
echo "  الخطط في البيان: ${#MANIFEST[@]} — $(for p in "${MANIFEST[@]}"; do printf '%s ' "$(basename "$p")"; done)"
echo "  معايير معلَنة في §٧: $n_declared"
echo "  معايير لها مالك:     $n_covered"

if [ "$n_declared" -lt "$MIN_CRITERIA" ]; then
  echo "  ❌ استُخرج $n_declared معيارًا فقط (الحدّ الأدنى $MIN_CRITERIA)."
  echo "     إمّا حُذفت معايير من §٧، وإمّا انكسر الاستخراج — وكلاهما يوقف البوابة."
  exit 1
fi

status=0
missing=$(comm -23 <(printf '%s\n' "$declared") <(printf '%s\n' "$covered"))
orphan=$(comm -13 <(printf '%s\n' "$declared") <(printf '%s\n' "$covered"))

if [ -n "$missing" ]; then
  echo "  ❌ معايير بلا مالك تحقّق:"
  printf '%s\n' "$missing" | sed 's/^/     /'
  status=1
fi
if [ -n "$orphan" ]; then
  echo "  ❌ وسوم تدّعي تغطية معيار غير معلَن في §٧:"
  printf '%s\n' "$orphan" | sed 's/^/     /'
  status=1
fi

[ $status -ne 0 ] && exit $status

echo "  ✅ كل معيار له مالك، وكل مالك يعلن معيارًا قائمًا."
echo
echo "  المعيار → المالك:"
for criterion in $declared; do
  owners=""
  for file in $(grep -rlE "${SOURCES[@]}" "@covers" "${SEARCH[@]}" 2>/dev/null); do
    if grep -oE "@covers +ق-$DIGITS+(, *ق-$DIGITS+)*" "$file" \
       | grep -oE "ق-$DIGITS+" | grep -qx "$criterion"; then
      owners+="$(basename "$file") "
    fi
  done
  printf "    %-7s %s\n" "$criterion" "$owners"
done
